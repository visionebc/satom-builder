#!/usr/bin/env bash
# Finish an update that an OLDER update runner applied.
#
# Vendored (reduced) from SATOM deploy/upgrade-converge.sh (see deploy/VENDORED.md).
#
# An update is applied by the runner INSTALLED on the node, not by the one in
# the package being applied. An older runner only knows the units and queue
# directories of its own release, so a unit or a directory introduced later is
# never installed, and the update still ends green. deploy/install-runner.sh is
# executed from the NEW (verified) tree by every runner, so it calls this
# script when its parent is the update runner.
#
# Idempotent. Run as root. NEVER fails an update: every problem is a WARN line
# and the exit status is always 0.
#
# By hand: sudo bash /opt/satom-builder/deploy/upgrade-converge.sh
set -uo pipefail

APP_DIR="${SATOM_BUILDER_APP_DIR:-/opt/satom-builder}"
DEPLOY_SRC="${SATOM_BUILDER_DEPLOY_SRC:-${APP_DIR}/deploy}"
SYSTEMD_DIR="/etc/systemd/system"
UPDATER="satom-builder-updater.service"

if [ "$(id -u)" -ne 0 ]; then
  echo "upgrade-converge.sh: must run as root." >&2
  exit 0
fi
cd / 2>/dev/null || true
warn() { echo "WARN converge: $*"; }

APP_USER="$(stat -c %U "$APP_DIR" 2>/dev/null || echo root)"

# ---- 1. queue directories the web app and the runner share ---------------
if [ "$APP_USER" != root ]; then
  for d in data data/update-requests data/update-status data/update-uploads; do
    [ -L "$APP_DIR/$d" ] && { warn "$APP_DIR/$d is a symlink; left alone"; continue; }
    [ -d "$APP_DIR/$d" ] && continue
    install -d -o "$APP_USER" -g "$APP_USER" -m 0750 "$APP_DIR/$d" \
      || warn "could not create $APP_DIR/$d"
  done
fi

# ---- 2. units the applying runner did not know about ---------------------
installed=()
fresh=()
for src in "$DEPLOY_SRC"/*.service "$DEPLOY_SRC"/*.timer "$DEPLOY_SRC"/*.path; do
  [ -f "$src" ] || continue
  unit="$(basename "$src")"
  dst="${SYSTEMD_DIR}/${unit}"
  [ -e "$dst" ] && continue
  if ! install -o root -g root -m 0644 "$src" "$dst"; then
    warn "could not install ${unit}"; continue
  fi
  installed+=("$unit")
  if [ "${unit%.service}" != "$unit" ] && [ "$unit" != "$UPDATER" ] && [ "$APP_USER" != root ]; then
    mkdir -p "${dst}.d"
    cat > "${dst}.d/10-app-user.conf" <<EOF
# Generated by SATOM Builder (installer / update runner). Do NOT edit by hand.
# Lives in a drop-in rather than in the unit because every update re-copies the
# deploy/ templates: the drop-in survives that.
[Service]
User=${APP_USER}
Group=${APP_USER}
EOF
  fi
  case "$unit" in *.path|*.timer) fresh+=("$unit") ;; esac
done
systemctl daemon-reload 2>/dev/null || true
for unit in "${fresh[@]+"${fresh[@]}"}"; do
  timeout 15 systemctl enable --now "$unit" >/dev/null 2>&1 || warn "could not enable ${unit}"
done
if [ "${#installed[@]}" -gt 0 ]; then
  echo "converge: units installed: ${installed[*]}"
else
  echo "converge: units already complete"
fi
exit 0
