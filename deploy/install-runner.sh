#!/usr/bin/env bash
# Install (or refresh) the ROOT-OWNED copy of the SATOM Builder update runner.
#
# Vendored from SATOM deploy/install-runner.sh (see deploy/VENDORED.md).
#
# WHY THIS EXISTS. satom-builder-updater.service runs as root. The application
# tree (/opt/satom-builder) is owned by the SERVICE ACCOUNT, so a runner
# executed from there would let the unprivileged web worker rewrite the code
# root is about to run -- and then enqueue a request, which it is designed to be
# able to do. That is a complete escalation, and it makes signature checking
# meaningless: a verifier the attacker can edit verifies nothing.
#
# So the runner, its signature verifier, the feed reader and the release-trust
# helper are copied to a root-owned directory outside the tree, a SYSTEM
# interpreter (never the venv) is picked, and the unit is pointed at them by a
# drop-in (not an edit: every update re-copies deploy/<unit>).
#
# Idempotent. Run as root. Called from:
#   * installers/install-satom-builder.sh   (fresh install / re-run)
#   * deploy/self_update_runner.py          (after every package apply, from a
#                                            root-only copy of the VERIFIED package)
#   * satom-builder reinstall runner        (manual)
set -euo pipefail

APP_DIR="${SATOM_BUILDER_APP_DIR:-/opt/satom-builder}"
LIB_DIR="/usr/local/lib/satom-builder-runner"
UNIT="satom-builder-updater.service"
DROPIN_DIR="/etc/systemd/system/${UNIT}.d"
ETC_DIR="/etc/satom-builder"
TRUST_DIR="${ETC_DIR}/update-keys"

# Every file root executes or reads as a trust input.
FILES="self_update_runner.py update_package.py upgrade_feed.py satom_builder_cli/release_trust.py"

# Where the payload is read from. Unset = the app tree's deploy/. The update
# runner sets it to a root-only staged copy of the verified package, and the
# CLI to a staged signed release when a release-trust anchor is installed.
DEPLOY_SRC="${SATOM_BUILDER_DEPLOY_SRC:-${APP_DIR}/deploy}"

if [ "$(id -u)" -ne 0 ]; then
  echo "install-runner.sh: must run as root (it writes ${LIB_DIR})." >&2
  exit 3
fi
for f in $FILES; do
  [ -f "${DEPLOY_SRC}/${f}" ] || {
    echo "install-runner.sh: missing ${DEPLOY_SRC}/${f}" >&2; exit 1; }
  # `cp -a` copies a link AS a link: root would run the file it points at on
  # every update, whatever this script verified. Refuse, never resolve.
  [ ! -L "${DEPLOY_SRC}/${f}" ] && [ ! -L "$(dirname "${DEPLOY_SRC}/${f}")" ] || {
    echo "install-runner.sh: ${DEPLOY_SRC}/${f} is (or sits under) a symlink -- refusing" >&2; exit 1; }
done

# A SYSTEM python >= 3.10, never the venv (the runner must work when the venv
# is broken -- that is when an offline package is applied) and never anything
# inside the app tree. RHEL 9's /usr/bin/python3 is 3.9: python3.11 is found.
pick_runner_python() {
  local c v
  for c in /usr/bin/python3 /usr/bin/python3.13 /usr/bin/python3.12 \
           /usr/bin/python3.11 /usr/bin/python3.10 \
           /usr/local/bin/python3.13 /usr/local/bin/python3.12 \
           /usr/local/bin/python3.11 /usr/local/bin/python3.10; do
    [ -x "$c" ] || continue
    case "$c" in "${APP_DIR}"/*) continue ;; esac
    v="$("$c" -c 'import sys;print("%d.%d" % sys.version_info[:2])' 2>/dev/null)" || continue
    case "$v" in
      3.1[0-9]|3.[2-9][0-9]) echo "$c"; return 0 ;;
    esac
  done
  return 1
}

RUN_PY="$(pick_runner_python)" || {
  echo "install-runner.sh: no system Python >= 3.10 found for the update runner." >&2
  echo "  Install python3.11 (or newer) and re-run:" >&2
  echo "    bash ${APP_DIR}/deploy/install-runner.sh" >&2
  exit 1
}

# Build beside, then swap: a half-copied runner is a runner that cannot roll back.
STAGE="${LIB_DIR}.new.$$"
rm -rf "$STAGE"
mkdir -p "$STAGE"
for f in $FILES; do
  cp -a "${DEPLOY_SRC}/${f}" "${STAGE}/$(basename "$f")"
done
chown -R root:root "$STAGE"
chmod 0755 "$STAGE"
find "$STAGE" -type f -exec chmod 0644 {} +

# The verifier must pass a self-test before it is trusted with an update.
"$RUN_PY" -I -c "
import importlib.util
spec = importlib.util.spec_from_file_location('up', '${STAGE}/update_package.py')
m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
seed = bytes(range(32))
pub = m.ed25519_public_from_seed(seed)
assert m.ed25519_verify(pub, b'satom-builder', m.ed25519_sign(seed, b'satom-builder'))
assert not m.ed25519_verify(pub, b'satom-builder', m.ed25519_sign(seed, b'other'))
assert m.PRODUCT == 'satom-builder' and m.SCHEMA == 'satom-builder.update-package/1'
" || {
  echo "install-runner.sh: the signature verifier failed its self-test -- refusing to install." >&2
  rm -rf "$STAGE"; exit 1
}

rm -rf "${LIB_DIR}.old"
[ -d "$LIB_DIR" ] && mv "$LIB_DIR" "${LIB_DIR}.old"
mv "$STAGE" "$LIB_DIR"
rm -rf "${LIB_DIR}.old"

# ---- point the unit at the root-owned copy -------------------------------
mkdir -p "$DROPIN_DIR"
cat > "${DROPIN_DIR}/10-root-copy.conf" <<EOF
# Generated by SATOM Builder (install-runner.sh). DO NOT EDIT.
# The runner runs as root from a root-owned copy with a system interpreter:
# code the service account can rewrite is never executed as root. A drop-in and
# not an edit, because every update re-copies deploy/${UNIT}.
[Service]
ExecStart=
ExecStart=${RUN_PY} -I ${LIB_DIR}/self_update_runner.py
Environment=SATOM_BUILDER_APP_DIR=${APP_DIR}
Environment=SATOM_BUILDER_TRUST_DIR=${TRUST_DIR}
EOF
chmod 0644 "${DROPIN_DIR}/10-root-copy.conf"

# ---- trust store ---------------------------------------------------------
# Empty is a valid state: this node then accepts no package yet.
mkdir -p "$TRUST_DIR"
chown root:root "$ETC_DIR" "$TRUST_DIR"
chmod 0755 "$ETC_DIR" "$TRUST_DIR"
# The rollback points hold venv copies and database backups: root only.
install -d -m 0700 -o root -g root /var/lib/satom-builder-rollback /var/lib/satom-builder-runner

# ---- release-signature trust anchor (OPTIONAL, opt-in) -------------------
# With a root-owned ${ETC_DIR}/release-trust.allowed_signers (or .pub), the
# root CLI's 'reinstall cli|runner' only installs a deploy/ that a release key
# signed. This script deliberately does NOT create the anchor: turning the
# enforcement on is an explicit operator act (docs/offline-update-packages.md).

systemctl daemon-reload 2>/dev/null || true

# ---- verify rather than assume ------------------------------------------
fail=0
for p in "$LIB_DIR" "$TRUST_DIR"; do
  owner="$(stat -c %U "$p")"; mode="$(stat -c %a "$p")"
  case "$owner:$mode" in
    root:755|root:0755) ;;
    *) echo "install-runner.sh: ${p} is ${owner} mode ${mode} -- expected root 755" >&2; fail=1 ;;
  esac
done
for f in $FILES; do
  owner="$(stat -c %U "${LIB_DIR}/$(basename "$f")")"
  [ "$owner" = root ] || { echo "install-runner.sh: ${LIB_DIR}/$(basename "$f") is ${owner}" >&2; fail=1; }
done
if [ -d /run/systemd/system ]; then
  ACTUAL="$(systemctl show -p ExecStart --value "$UNIT" 2>/dev/null || true)"
  case "$ACTUAL" in
    *"${LIB_DIR}/self_update_runner.py"*) ;;
    *) echo "install-runner.sh: ${UNIT} still starts: ${ACTUAL}" >&2; fail=1 ;;
  esac
fi
[ "$fail" -eq 0 ] || exit 1

echo "SATOM Builder update runner hardened:"
echo "  code       : ${LIB_DIR} (root:root, system python ${RUN_PY})"
echo "  trust store: ${TRUST_DIR} ($(find "$TRUST_DIR" -maxdepth 1 -name '*.pub' | wc -l) key(s))"

# ---- finish an update an older runner applied ----------------------------
# The one root-side file every runner executes from the NEW (verified) tree is
# this script, so it is where an older runner's update gets finished
# (deploy/upgrade-converge.sh). Only when the update runner is our parent.
parent="$(tr '\0' ' ' < "/proc/${PPID}/cmdline" 2>/dev/null || true)"
if [ -f "${DEPLOY_SRC}/upgrade-converge.sh" ]; then
  case "$parent" in
    *self_update_runner.py*)
      SATOM_BUILDER_APP_DIR="$APP_DIR" SATOM_BUILDER_DEPLOY_SRC="$DEPLOY_SRC" \
        timeout 150 bash "${DEPLOY_SRC}/upgrade-converge.sh" || true ;;
  esac
fi
